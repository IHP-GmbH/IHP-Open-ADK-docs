"""Shared helpers for the documentation generators.

Every generator in this directory reads the pinned submodules under ``src/``
and writes into ``docs/``. Nothing normative on this site is typed by hand, so
a change in the source repositories shows up as a diff in the generated files,
which is what the CI drift gate checks.
"""

import json
import os
import sys

DOCS_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REPO_ROOT = os.path.dirname(DOCS_DIR)
SRC_DIR = os.path.join(REPO_ROOT, "src")

ADK = os.path.join(SRC_DIR, "IHP-Open-ADK")
TOOLS = os.path.join(SRC_DIR, "ADK-Tools")
SPEC = os.path.join(SRC_DIR, "chiplet-spec")
INTERPOSER = os.path.join(SRC_DIR, "OpenIntM4TM2")
INTERCONNECT = os.path.join(SRC_DIR, "IHP-Interconnect-IntM4TM2")

GENERATED_BANNER = (
    ".. Generated by docs/scripts/{script}. Do not edit by hand.\n"
    ".. Regenerate with: make -C docs preprocess\n"
)


def fail(message):
    """Abort the build with a diagnostic.

    Generators fail loudly rather than emitting a partial table: a silently
    truncated rule list reads as "these are all the rules" when it is not.
    """
    sys.stderr.write("error: {}\n".format(message))
    raise SystemExit(1)


def require_submodule(path, name):
    if not os.path.isdir(path):
        fail(
            "submodule {} is not checked out at {}. "
            "Run: git submodule update --init".format(name, path)
        )
    return path


def read_json(path):
    if not os.path.isfile(path):
        fail("expected file not found: {}".format(path))
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def read_text(path):
    if not os.path.isfile(path):
        fail("expected file not found: {}".format(path))
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def write_csv(path, rows):
    """Write a headerless CSV.

    Headers live in the ``csv-table`` directive, matching the convention in
    IHP-Open-PDK-docs.
    """
    import csv

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, quoting=csv.QUOTE_ALL)
        for row in rows:
            writer.writerow(row)
    print("wrote {} ({} rows)".format(os.path.relpath(path, REPO_ROOT), len(rows)))


def write_text(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    print("wrote {}".format(os.path.relpath(path, REPO_ROOT)))


def format_number(value):
    """Render a rule value without trailing zeros, keeping it readable."""
    number = float(value)
    if number == int(number):
        return str(int(number))
    return ("%f" % number).rstrip("0").rstrip(".")
